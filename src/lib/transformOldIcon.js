//"star-outline" → { lib: 'keen', icon: 'star', type: 'outline' } (FORMATO DO <KeenIcon icon style>)
//"lucide:Music"  → { lib: 'lucide', icon: 'Music' }
const keenIconFromName = (mappedIcon) => {

    if (mappedIcon.startsWith('lucide:')) {
        return { lib: 'lucide', icon: mappedIcon.slice(7), type: 'outline' }
    }

    var iconName, type
    if (mappedIcon.substr(-7) === 'outline') {
        iconName = mappedIcon.slice(0, -8)
        type = 'outline'
    } else if (mappedIcon.substr(-7) === 'duotone') {
        iconName = mappedIcon.slice(0, -8)
        type = 'duotone'
    } else {
        iconName = mappedIcon.slice(0, -6)
        type = 'solid'
    }

    return { lib: 'keen', icon: iconName, type: type || 'outline' }

}

//POSIÇÕES DO SPRITE QUE TÊM KEENICON, SEM REPETIR ÍCONE (A PRIMEIRA POSIÇÃO DE CADA UM VENCE).
//USADO PELO SELETOR DE ÍCONE DO EDITOR DE MÓDULOS, QUE CONTINUA GRAVANDO coluna/linha
export const OLD_ICON_OPTIONS = (() => {

    const vistos = new Set()
    const opcoes = []

    Object.entries(OLD_ICON_MAP).forEach(([key, mappedIcon]) => {

        if (!mappedIcon || vistos.has(mappedIcon)) return
        vistos.add(mappedIcon)

        const [linha, coluna] = key.split('/')
        opcoes.push({ coluna, linha, name: mappedIcon, ...keenIconFromName(mappedIcon) })

    })

    return opcoes

})()

export const transformOldIcon = (iconString) => {

    //AÇÃO SEM ÍCONE (undefined/null) CAI NO ÍCONE PADRÃO EM VEZ DE QUEBRAR A TELA
    iconString = String(iconString ?? '').replace(/figura-(black|white)\s*/i, '')

    const colMatch = iconString.match(/c(\d+)/i)
    const rowMatch = iconString.match(/l(\d+)/i)

    if (!colMatch || !rowMatch) {
        return { lib: 'keen', icon: 'html', type: 'outline' }
    }

    const col = colMatch[1]
    const row = rowMatch[1]
    const key = `${row}/${col}`

    const mappedIcon = OLD_ICON_MAP[key] || ''

    if (!mappedIcon) return { lib: 'keen', icon: 'html', type: 'outline' }

    return keenIconFromName(mappedIcon)

}

