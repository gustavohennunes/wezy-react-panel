//ÍCONE DE UM ITEM DO panel/menus (SIDEBAR E ACESSO RÁPIDO DO DASHBOARD)
export const iconeDoMenu = (item) => {
    const pagina = /[?&]pag=([^&]+)/.exec(item?.path || '')?.[1]
    return ICONE_POR_PAGINA[pagina] || transformOldIcon(item?.icon || '')
}
